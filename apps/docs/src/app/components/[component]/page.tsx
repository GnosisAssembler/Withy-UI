export function generateStaticParams() {
  return (Object.keys(titles) as ComponentSlug[]).map((component) => ({ component }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ component: string }>;
}): Promise<Metadata> {
  const { component } = await params;
  const title = titles[component as ComponentSlug];
  return { title: title ?? "Components" };
}

export default async function ComponentPage({
  params,
}: {
  params: Promise<{ component: string }>;
}) {
  const { component } = await params;
  if (!(component in titles)) notFound();
  return <ComponentsDocsTemplate component={component as ComponentSlug} />;
}
